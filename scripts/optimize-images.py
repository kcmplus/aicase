#!/usr/bin/env python3
"""Build reproducible, content-addressed storefront previews; keep source assets."""
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from management_api.image_processing import display_variants, normalized_image

assets = ROOT / "frontend/storefront/assets"
output = assets / "optimized"
output.mkdir(exist_ok=True)
manifest = {}
before = after = 0
for source in sorted(assets.rglob("*")):
    if source.suffix.lower() not in (".png", ".jpg", ".jpeg") or output in source.parents:
        continue
    if source.name == "popomo-brand.jpg":
        # The existing SVG shows only this wordmark rectangle from a tall brand board.
        with Image.open(source) as image:
            wordmark = image.crop((124, 224, 1159, 424))
            wordmark.thumbnail((600, 200), Image.Resampling.LANCZOS)
            wordmark.save(assets / "popomo-wordmark.webp", "WEBP", quality=92, method=6)
        continue
    with Image.open(source) as original:
        image = normalized_image(original)
    versions = []
    for width, height, data in display_variants(image):
        digest = hashlib.sha256(data).hexdigest()[:20]
        target = output / f"{source.stem}-{digest}-{width}.webp"
        target.write_bytes(data)
        versions.append({"src": "/" + str(target.relative_to(assets.parent)), "width": width, "height": height})
    manifest["/" + str(source.relative_to(assets.parent))] = {"width": image.width, "height": image.height, "variants": versions}
    before += source.stat().st_size
    after += (assets.parent / versions[-1]["src"].lstrip("/")).stat().st_size
(assets.parent / "image-manifest.js").write_text("// Generated by scripts/optimize-images.py. Keep original paths in saved designs.\nexport default " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(json.dumps({"images": len(manifest), "original_bytes": before, "largest_preview_bytes": after, "reduction_percent": round(100 * (1 - after / before), 1)}, indent=2))
